static float SpeedAbs(float speed)
{
  if (speed < 0)
  {
    return -speed;
  }

  return speed;
}

static uint8_t PIDOutToPWM(float out)
{
  if (out <= 0.0f)
  {
    return 0;
  }

  if (out >= 99.0f)
  {
    return 99;
  }

  return (uint8_t)out;
}

static void SpeedControl_Update(void)
{
  Left_speed = Encoder_GetSpeedRPS(1);
  Right_speed = Encoder_GetSpeedRPS(2);

  if (Left_Speed_PID.target <= 0.0f)
  {
    Left_Speed_PID.target = 0.0f;
    PID_Reset(&Left_Speed_PID);
    Left_Out = 0;
    MotorSetLeftPWM(0);
  }
  else
  {
    Left_Speed_PID.actual = SpeedAbs(Left_speed);
    Left_Out = (int16_t)PID_Calculate(&Left_Speed_PID);
    MotorSetLeftPWM(PIDOutToPWM(Left_Out));
  }

  if (Right_Speed_PID.target <= 0.0f)
  {
    Right_Speed_PID.target = 0.0f;
    PID_Reset(&Right_Speed_PID);
    Right_Out = 0;
    MotorSetRightPWM(0);
  }
  else
  {
    Right_Speed_PID.actual = SpeedAbs(Right_speed);
    Right_Out = (int16_t)PID_Calculate(&Right_Speed_PID);
    MotorSetRightPWM(PIDOutToPWM(Right_Out));
  }
}

